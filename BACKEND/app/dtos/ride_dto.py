"""Bodies, queries and responses of /rides."""

import base64
import binascii
from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import AwareDatetime, Field, field_validator, model_validator

from ..repository.ride_repository import DriverInfo, Position, Rating, Ride, Stop
from ..services import ride_rules
from ..services.account_rules import clean_name
from ..services.ride_service import Estimate, RidePage
from .base import ApiModel, InputModel, apply_rule, field_error

ADDRESS_MAX_LENGTH = 255

Purpose = Literal["employment", "training", "health", "administrative", "other"]
RideStatus = Literal["awaiting_payment", "pending", "accepted", "in_progress", "completed", "cancelled", "expired"]
PaymentStatus = Literal["not_required", "pending", "paid", "refunded"]


# --- Request bodies ----------------------------------------------------------

class StopBody(InputModel):
    """A pickup or drop-off point, as proposed by GET /places."""

    address: str = Field(max_length=ADDRESS_MAX_LENGTH, examples=["Mairie de Matoury"])
    lat: float = Field(ge=-90, le=90, examples=[4.847])
    lng: float = Field(ge=-180, le=180, examples=[-52.331])
    commune_id: int = Field(ge=1)

    @field_validator("address")
    @classmethod
    def _address(cls, value: str) -> str:
        return apply_rule(clean_name, value)

    def to_stop(self) -> Stop:
        return Stop(address=self.address, lat=self.lat, lng=self.lng, commune_id=self.commune_id)


class EstimateBody(InputModel):
    pickup: StopBody
    dropoff: StopBody


class BookRideBody(InputModel):
    """The price is not sent: the API computes it."""

    # Generated by the phone once per booking, sent again as is on a retry.
    client_request_id: UUID
    purpose: Purpose
    pickup: StopBody
    dropoff: StopBody
    # null: leave now. Otherwise, at least 30 minutes from now.
    scheduled_at: AwareDatetime | None = None

    @field_validator("scheduled_at")
    @classmethod
    def _scheduled_at(cls, value: datetime | None) -> datetime | None:
        return apply_rule(ride_rules.check_scheduled_at, value)


class RideListQuery(InputModel):
    # upcoming: not finished, all of them. past: finished, by pages.
    when: Literal["upcoming", "past"]
    # nextCursor of the previous page of past rides; absent for the first one.
    cursor: str | None = None

    @field_validator("cursor")
    @classmethod
    def _cursor(cls, value: str | None) -> str | None:
        if value is not None:
            apply_rule(decode_cursor, value)
        return value

    @model_validator(mode="after")
    def _cursor_for_past_only(self) -> "RideListQuery":
        if self.cursor is not None and self.when != "past":
            raise field_error("Seuls les trajets passés sont envoyés par pages.")
        return self

    def position(self) -> Position | None:
        return decode_cursor(self.cursor) if self.cursor is not None else None


class RateRideBody(InputModel):
    score: int = Field(ge=ride_rules.MIN_SCORE, le=ride_rules.MAX_SCORE, examples=[5])
    # Optional: empty or blank is stored as null.
    comment: str | None = Field(None, examples=["Chauffeur ponctuel et aimable."])

    @field_validator("comment")
    @classmethod
    def _comment(cls, value: str | None) -> str | None:
        return apply_rule(ride_rules.clean_comment, value)


# --- Responses ---------------------------------------------------------------

class EstimateDto(ApiModel):
    distance_km: float = Field(examples=[11.4])
    price_cents: int = Field(examples=[1712])
    voucher_amount_cents: int
    rider_amount_cents: int


class StopDto(ApiModel):
    address: str
    lat: float
    lng: float
    commune_id: int


class RatingDto(ApiModel):
    score: int = Field(examples=[5])
    comment: str | None
    created_at: datetime


class RideVehicleDto(ApiModel):
    plate: str = Field(examples=["AA-000-AA"])
    model: str = Field(examples=["Modèle fictif"])
    is_accessible: bool


class RideDriverDto(ApiModel):
    """The driver, for the rider and the staff. Phone only while the ride is under way."""

    id: int
    first_name: str
    phone: str | None
    average_score: float | None = Field(examples=[4.7])
    vehicle: RideVehicleDto


class RideRiderDto(ApiModel):
    """The rider, for their driver while the ride is under way, and for the staff."""

    first_name: str
    phone: str


class RideDto(ApiModel):
    id: int
    status: RideStatus
    channel: Literal["app", "phone"]
    purpose: Purpose
    pickup: StopDto
    dropoff: StopDto
    scheduled_at: datetime | None
    needs_accessible_vehicle: bool
    distance_km: float
    price_cents: int
    voucher_amount_cents: int
    rider_amount_cents: int
    payment_status: PaymentStatus
    rating: RatingDto | None
    driver: RideDriverDto | None
    rider: RideRiderDto | None
    created_at: datetime
    paid_at: datetime | None
    expires_at: datetime
    accepted_at: datetime | None
    started_at: datetime | None
    completed_at: datetime | None
    cancelled_at: datetime | None
    expired_at: datetime | None


class RideListDto(ApiModel):
    items: list[RideDto]
    # To send back as `cursor` for the next page; null on the last page (and for upcoming rides).
    next_cursor: str | None


def estimate_to_dto(estimate: Estimate) -> EstimateDto:
    return EstimateDto(
        distance_km=float(estimate.distance_km),
        price_cents=estimate.price_cents,
        voucher_amount_cents=estimate.voucher_amount_cents,
        rider_amount_cents=estimate.rider_amount_cents,
    )


def ride_to_dto(ride: Ride) -> RideDto:
    return RideDto(
        id=ride.id,
        status=ride.status,
        channel=ride.channel,
        purpose=ride.purpose,
        pickup=_stop_to_dto(ride.pickup),
        dropoff=_stop_to_dto(ride.dropoff),
        scheduled_at=ride.scheduled_at,
        needs_accessible_vehicle=ride.needs_accessible_vehicle,
        distance_km=float(ride.distance_km),
        price_cents=ride.price_cents,
        # No voucher yet (not in the MVP schema): the rider pays the whole price.
        voucher_amount_cents=0,
        rider_amount_cents=ride.price_cents,
        payment_status=ride.payment_status,
        rating=_rating_to_dto(ride.rating) if ride.rating else None,
        driver=_driver_to_dto(ride.driver) if ride.driver else None,
        rider=RideRiderDto(first_name=ride.rider.first_name, phone=ride.rider.phone) if ride.rider else None,
        created_at=ride.created_at,
        paid_at=ride.paid_at,
        expires_at=ride.expires_at,
        accepted_at=ride.accepted_at,
        started_at=ride.started_at,
        completed_at=ride.completed_at,
        cancelled_at=ride.cancelled_at,
        expired_at=ride.expired_at,
    )


def ride_list_to_dto(rides: list[Ride], next_position: Position | None = None) -> RideListDto:
    return RideListDto(
        items=[ride_to_dto(ride) for ride in rides],
        next_cursor=encode_cursor(next_position) if next_position else None,
    )


def ride_page_to_dto(page: RidePage) -> RideListDto:
    return ride_list_to_dto(page.rides, page.next_position)


# --- Cursor ------------------------------------------------------------------
# Opaque for the phone: it sends it back as is. Inside, the booking time and
# the id of the last ride of the page.
_CURSOR_SEPARATOR = "|"
INVALID_CURSOR = "Lien de page invalide. Rechargez la liste."


def encode_cursor(position: Position) -> str:
    raw = f"{position.created_at.isoformat()}{_CURSOR_SEPARATOR}{position.ride_id}"
    return base64.urlsafe_b64encode(raw.encode()).decode()


def decode_cursor(cursor: str) -> Position:
    """ValueError if the cursor was not made by encode_cursor()."""
    try:
        created_at, ride_id = base64.urlsafe_b64decode(cursor.encode()).decode().split(_CURSOR_SEPARATOR)
        position = Position(created_at=datetime.fromisoformat(created_at), ride_id=int(ride_id))
    except (binascii.Error, UnicodeDecodeError, ValueError):
        raise ValueError(INVALID_CURSOR) from None
    if position.created_at.tzinfo is None:
        raise ValueError(INVALID_CURSOR)
    return position


def _rating_to_dto(rating: Rating) -> RatingDto:
    return RatingDto(score=rating.score, comment=rating.comment, created_at=rating.created_at)


def _stop_to_dto(stop: Stop) -> StopDto:
    return StopDto(address=stop.address, lat=stop.lat, lng=stop.lng, commune_id=stop.commune_id)


def _driver_to_dto(driver: DriverInfo) -> RideDriverDto:
    return RideDriverDto(
        id=driver.id,
        first_name=driver.first_name,
        phone=driver.phone,
        average_score=round(driver.average_score, 1) if driver.average_score is not None else None,
        vehicle=RideVehicleDto(
            plate=driver.vehicle_plate, model=driver.vehicle_model, is_accessible=driver.vehicle_is_accessible
        ),
    )
